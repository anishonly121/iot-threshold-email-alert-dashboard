require('dotenv').config();
const express=require('express');const path=require('node:path');
const app=express();app.disable('x-powered-by');app.use(express.json({limit:'8kb'}));
app.use((req,res,next)=>{res.setHeader('X-Content-Type-Options','nosniff');res.setHeader('Referrer-Policy','no-referrer');next();});
app.post('/api/send-alert',require('./api/send-alert'));
app.get('/api/health',(_,res)=>res.json({status:'ok'}));
for(const file of ['index.html','app.js','style.css'])app.get(file==='index.html'?'/':'/'+file,(_,res)=>res.sendFile(path.join(__dirname,file)));
app.use('/assets',express.static(path.join(__dirname,'assets'),{dotfiles:'deny'}));
app.use((_,res)=>res.status(404).json({message:'Not found'}));
app.use((err,req,res,next)=>res.status(err.status||500).json({message:'Request failed'}));
if(require.main===module)app.listen(process.env.PORT||8081,'127.0.0.1',()=>console.log('IoT dashboard ready'));
module.exports=app;
